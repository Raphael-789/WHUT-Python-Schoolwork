print(bin(10))

# 输出：0b1010 内置函数bin(x)：将整数 x 转换为二进制字符串（带 0b 前缀）。


print(oct(10))

# 输出：0o12 内置函数oct(x)：将整数 x 转换为八进制字符串（带 0o 前缀）。


print(hex(255))

# 输出：0xff 内置函数hex(x)：将整数 x 转换为十六进制字符串（带 0x 前缀）。


print(int('1010', 2))

# 输出：10（二进制转十进制）内置函数int(s, base)：将指定进制的字符串 s 转换为十进制整数（base 为进制数，如 2、8、16）。


print(int('ff', 16))

# 输出：255（十六进制转十进制） 内置函数，同上。
