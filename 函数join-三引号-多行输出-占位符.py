a=input()

#最低级的方法，我想你不会用的。第一，多行print;第二，未使用占位符。
print('|++++++++++++++++++++++|')
print('|                      |')
print('|   Welcome to WHUT    |')
print('|                      |')
print('|++++++++++++++++++++++|')
print('欢迎您，',a,'同学！',sep='')

#上文sep分隔符“seprator”默认是空格，这也是一个点。

#想将这 6 行打印语句简化成一行代码，可以使用字符串的连接或多行字符串实现：  

# 方法1：使用换行符连接。

print('|++++++++++++++++++++++|\n|                      |\n|   Welcome to WHUT    |\n|                      |\n|++++++++++++++++++++++|\n欢迎您，{}同学！'.format(a))

#解析：
#首先f'''...''' 创建了一个多行的 f-string。
#字符串中的 {a} 是一个占位符。Python 在打印时，会找到变量 a，获取它的输入值，然后将 {a} 替换为 "孙悟空"之类的输入值。
#最终输出的结果中，{a} 就变成了输入值。

# 方法2：使用三引号多行字符串。三引号 ''' 或 """ 允许字符串跨越多行，保持原始的换行格式，非常适合用来定义这种需要保留格式的文本块。
#f 前缀与三引号结合，就可以创建一个既保留格式又能嵌入变量的多行字符串。

print(f'''|++++++++++++++++++++++|
|                      |
|   Welcome to WHUT    |
|                      |
|++++++++++++++++++++++|
欢迎您，{a}同学！''')

# 方法3：使用字符串join方法，Python 中 字符串（str）类型 的一个内置方法（函数），
#将一个可迭代对象（如列表、元组、字符串等）中的所有元素，用调用 join() 的字符串作为分隔符，连接成一个新的字符串。

print('\n'.join([
    '|++++++++++++++++++++++|',
    '|                      |',
    '|   Welcome to WHUT    |',
    '|                      |',
    '|++++++++++++++++++++++|',
    f'欢迎您，{a}同学！'
]))
